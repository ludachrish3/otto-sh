def _lf(text: str) -> str:
    """Return commit *text* with CRLF and CR line endings turned into LF."""
    return text.replace("\r\n", "\n").replace("\r", "\n")


def docs_conf_value(name: str) -> object:
    """Read one literal assignment from ``docs/conf.py`` without executing it."""
    tree = ast.parse((DOCS_DIR / "conf.py").read_text(encoding="utf-8"))
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(
            isinstance(t, ast.Name) and t.id == name for t in node.targets
        ):
            return ast.literal_eval(node.value)
    raise RenderError(f"docs/conf.py assigns no {name}")


@functools.cache
def _markdown() -> MarkdownIt:
    """MyST's Markdown parser, with the extensions ``docs/conf.py`` enables."""
    extensions = docs_conf_value("myst_enable_extensions")
    if not isinstance(extensions, list):
        raise RenderError(f"docs/conf.py's myst_enable_extensions is not a list: {extensions!r}")
    config = MdParserConfig(enable_extensions=set(extensions))
    return create_md_parser(config, RendererHTML)


def myst_tokens(markdown: str, env: "dict | None" = None) -> "list[Token]":
    """Return the tokens MyST parses *markdown* into, as the docs build would."""
    return _markdown().parse(markdown, {} if env is None else env)


def _allowed(token: Token) -> bool:
    """Whether *token* and its children are plain Markdown commit text may hold."""
    if token.type == "fence":
        return _LANGUAGE.fullmatch(token.info.strip()) is not None
    if token.type == "link_open":
        return urlsplit(str(token.attrs.get("href", ""))).scheme in ("http", "https")
    if token.type not in _BLOCK_TOKENS | _INLINE_TOKENS:
        return False
    return all(_allowed(child) for child in token.children or [])


_PARAGRAPH = ["paragraph_open", "inline", "paragraph_close"]


def _paragraph(tokens: "list[Token]") -> "list[Token] | None":
    """Return the inline children of *tokens* when they are one paragraph, else None."""
    if [t.type for t in tokens] != _PARAGRAPH:
        return None
    return tokens[1].children or []


def is_plain(markdown: str, *, inline: bool) -> bool:
    """Whether *markdown* is plain Markdown that cannot spill past its own end.

    It is parsed with a sentinel paragraph after it, which must survive as
    its own paragraph, so an unclosed fence cannot swallow the page below.
    *inline* fragments must be one paragraph. A link reference definition is
    refused too: it would vanish from the page.
    """
    env: dict = {}
    tokens = myst_tokens(f"{markdown}\n\n{_SENTINEL}", env)
    body, end = tokens[: -len(_PARAGRAPH)], tokens[-len(_PARAGRAPH) :]
    sentinel = _paragraph(end)
    if env.get("references") or sentinel is None or end[1].content != _SENTINEL:
        return False
    if inline and _paragraph(body) is None:
        return False
    return all(_allowed(token) for token in body)


def escape_markdown_html(text: str) -> str:
    """Turn ``<`` into ``&lt;`` outside backtick code spans, so ``<id>`` reads as text.

    A convenience, not the guard: :func:`is_plain` refuses any HTML left.
    """
    text = _lf(text)
    out, pos = [], 0
    for span in _CODE_SPAN.finditer(text):
        out += [text[pos : span.start()].replace("<", "&lt;"), span.group(0)]
        pos = span.end()
    out.append(text[pos:].replace("<", "&lt;"))
    return "".join(out)


def _fence(text: str, info: str) -> str:
    """Fence *text* with more backticks than any run inside it."""
    longest = max((len(run) for run in re.findall(r"`+", text)), default=0)
    ticks = "`" * max(3, longest + 1)
    return f"{ticks}{info}\n{text}\n{ticks}"


def _code_span(text: str) -> str:
    """Return *text* as a code span that shows it exactly, backticks included."""
    longest = max((len(run) for run in re.findall(r"`+", text)), default=0)
    ticks = "`" * (longest + 1)
    pad = " " if text[:1] in "` " or text[-1:] in "` " else ""
    return f"{ticks}{pad}{text}{pad}{ticks}"


def inline_text(text: str) -> str:
    """Return one line of commit text as Markdown: itself when plain, else a code span."""
    escaped = escape_markdown_html(text)
    return escaped if is_plain(escaped, inline=True) else _code_span(_lf(text))


def _link(label: str, raw: str, href: str) -> str:
    """``[label](href)``, unless *label* would retarget it; then *raw* as code is the label.

    A label such as ``x](https://example.invalid)`` closes the bracket early,
    so the link is parsed back and must be one link to *href*, nothing else.
    """
    candidate = f"[{label}]({href})"
    inner = _paragraph(myst_tokens(candidate)) or []
    ok = (
        bool(inner)
        and inner[0].type == "link_open"
        and inner[0].attrs.get("href") == href
        and inner[-1].type == "link_close"
        and all(t.type != "link_open" and _allowed(t) for t in inner[1:-1])
    )
    return candidate if ok else f"[{_code_span(raw)}]({href})"


def _example_lines(lines: "list[str]") -> "list[bool]":
    """Mark each line that is part of an example.

    An example is a run indented by two or more spaces. A run directly below a
    list item (or below that item's continuation), with no blank line between,
    continues the item instead, so it stays prose.
    """
    marks, in_item = [], False
    for line in lines:
        if not line.strip():
            marks.append(False)
            in_item = False
        elif _INDENTED.match(line):
            marks.append(not in_item)
        else:
            marks.append(False)
            in_item = bool(_LIST_ITEM.match(line))
    return marks


def format_remediation(text: str) -> str:
    """Return the Markdown a footer text renders as.

    An example (see :func:`_example_lines`) becomes a dedented ``text`` fence
    with a blank line on each side; everything else is prose, with
    :func:`escape_markdown_html` applied. When the result is not
    :func:`is_plain`, the whole text is shown verbatim in one ``text`` fence.
    """
    lines = _lf(text).split("\n")
    marks = _example_lines(lines)
    blocks: list[str] = []
    i = 0
    while i < len(lines):
        j = i
        while j < len(lines) and marks[j] == marks[i]:
            j += 1
        run = "\n".join(lines[i:j])
        block = _fence(textwrap.dedent(run), "text") if marks[i] else escape_markdown_html(run)
        if block.strip("\n"):
            blocks.append(block.strip("\n"))
        i = j
    markdown = "\n\n".join(blocks)
    return markdown if is_plain(markdown, inline=False) else _fence(_lf(text), "text")


