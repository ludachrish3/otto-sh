"""Render one release-notes page per otto release into ``docs/release-notes/``.

Run from the repo root::

    uv run python -m scripts.render_release_notes           # write the pages
    uv run python -m scripts.render_release_notes --check   # render, write nothing

The pages have two sources, and no third:

* **git-cliff** (``git-cliff --context --offline`` over the repository's own
  ``cliff.toml``) says which releases exist, which commits each holds, when it
  was tagged and which group (Added, Fixed, ...) each commit falls in. A
  commit git-cliff skips appears nowhere.
* **``scripts/release_events.py``** says everything else: whether a commit is
  breaking (the census verdict, not git-cliff's own ``breaking`` flag), its
  remediation text, its corrections, its scopes and subject, whether it is
  maintainer-only, and its message without trailers. This script never
  splits a commit message itself.

A page lists new features and bug fixes, then every breaking change with its
full remediation. Maintainer-only commits are left out. Pages start at
:data:`FIRST_RELEASE`; CHANGELOG.md holds every release, older ones included.
Commit text is Markdown by contract (docs/contributing.md), and only plain
Markdown passes: each fragment (a subject, a scope, a footer text) is parsed
by MyST's own parser, configured as ``docs/conf.py`` configures it, and a
fragment holding any token outside :data:`_BLOCK_TOKENS` and
:data:`_INLINE_TOKENS` (raw HTML, a directive, a role, a heading, a
blockquote, ...) is shown whole and verbatim, as code. Nothing is dropped.

The pages are git-ignored and rendered at docs build time; ``.stamp`` in the
pages directory skips the render when no input changed. ``docs/conf.py`` calls
:func:`sphinx_setup`, which turns Sphinx's smart quotes off on these pages, so
a ``--flag`` in commit text keeps its two hyphens.
"""

