# Reading.
# ---------------------------------------------------------------------------


def _context(repo: Path, cliff: str) -> "list[dict]":
    """Return git-cliff's tagged releases, newest first, after the refusals."""
    shallow = _git(repo, "rev-parse", "--is-shallow-repository").stdout.strip()
    if shallow == "true":
        raise RenderError(
            f"{repo} is a shallow clone, so its releases are incomplete; "
            "fetch full history with tags (git fetch --unshallow --tags)"
        )
    argv = [cliff, "--config", str(repo / "cliff.toml"), "--offline", "--context"]
    try:
        proc = subprocess.run(argv, cwd=repo, capture_output=True, text=True, check=False)  # noqa: S603 -- fixed argv; git-cliff from PATH
    except FileNotFoundError as err:
        raise RenderError(
            f"{cliff} is not on PATH; it is a dev dependency, so run `uv sync` "
            "and render through `uv run`"
        ) from err
    if proc.returncode != 0:
        raise RenderError(f"{' '.join(argv)} exited {proc.returncode}:\n{proc.stderr}")
    releases = [r for r in json.loads(proc.stdout) if r["version"] is not None]
    if not releases:
        raise RenderError(f"{repo} has no tagged release; tag one (v<X.Y.Z>) first")
    return releases


def _version(tag: str) -> str:
    """Return *tag*'s version without the ``v``; refuse a tag that is no release."""
    match = _RELEASE_TAG.match(tag)
    if match is None:
        raise RenderError(
            f"tag {tag!r} matches cliff.toml's tag_pattern but is not a release "
            f"(v<X.Y.Z>, optionally rcN), and it takes commits from a real release; "
            f"delete the stray local tag (git tag -d {tag})"
        )
    return match["version"]


def _release(repo: Path, version: str, context: dict, rev_range: str) -> Release:
    """Join one git-cliff release to ``release_events`` over *rev_range*, by full sha."""
    events = {e.commit.sha: e for e in release_events.release_events(repo, rev_range).events}
    commits = {c.sha: c for c in release_events.read_commits(repo, rev_range)}
    entries = []
    for item in context["commits"]:
        commit = commits.get(item["id"])
        if commit is None:
            raise RenderError(
                f"git-cliff puts {item['id'][:12]} in v{version}, but git's {rev_range} "
                "does not hold it; fetch full history with tags"
            )
        event = events.get(commit.sha)
        entries.append(
            Entry(
                commit=commit,
                group=item["group"],
                scope=", ".join(release_events.commit_scopes(commit.subject)) or None,
                subject=release_events.description(commit.subject),
                breaking=event is not None,
                remediation=release_events.remediation(commit),
                corrects=event.corrections if event else [],
            )
        )
    date = datetime.fromtimestamp(context["timestamp"], tz=timezone.utc).strftime("%Y-%m-%d")
    return Release(version=version, date=date, entries=entries)


def _link_corrections(releases: "list[Release]") -> None:
    """Point each shown target at the shown entry that marked it breaking.

    A target with no page, or one its page does not show, gets no pointer: the
    correcting entry is then its only mention.
    """
    shown = {e.commit.sha: e for r in releases for e in r.entries if e.shown}
    for release in releases:
        for entry in release.entries:
            if not entry.shown:
                continue
            for correction in entry.corrects:
                target = shown.get(correction.target)
                if target is not None:
                    target.corrected_by.append(f"{release.version}#{entry.label}")


def read_releases(repo: Path, *, cliff: str = "git-cliff") -> "list[Release]":
    """Return the releases with a page, newest first, as git-cliff orders them.

    Every tagged release is checked for a stray tag; only those at or above
    :data:`FIRST_RELEASE` are read further. The first release, which has no
    predecessor, reads its tag's whole history.
    """
    context = _context(repo, cliff)
    versions = [_version(r["version"]) for r in context]
    releases = []
    for i, (version, release) in enumerate(zip(versions, context, strict=True)):
        if not has_page(version):
            continue
        tag = release["version"]
        rev_range = f"{context[i + 1]['version']}..{tag}" if i + 1 < len(context) else tag
        releases.append(_release(repo, version, release, rev_range))
    _link_corrections(releases)
    return releases


