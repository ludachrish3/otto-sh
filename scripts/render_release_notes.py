def _digest(repo: Path) -> str:
    """Hash every input of the pages: the tags, the URL, this script, the model, the config."""
    digest = hashlib.sha256(tag_state(repo).encode())
    digest.update(repo_url().encode())
    cliff = repo / "cliff.toml"
    for path in [Path(__file__), Path(release_events.__file__)]:
        digest.update(path.read_bytes())
    digest.update(cliff.read_bytes() if cliff.is_file() else b"")
    # The Markdown allowlist parses with the extensions docs/conf.py enables.
    digest.update((DOCS_DIR / "conf.py").read_bytes())
    return digest.hexdigest()


def _fresh(digest: str) -> bool:
    """Whether the stamp holds *digest* and the index, and every page it lists exists.

    A stamp that is missing, unreadable, empty or lists no index is stale.
    """
    try:
        recorded, *names = (PAGES_DIR / STAMP).read_text(encoding="utf-8").splitlines()
    except (OSError, UnicodeDecodeError, ValueError):
        return False
    return (
        recorded == digest
        and "index.md" in names
        and all((PAGES_DIR / name).is_file() for name in names)
    )


def _write(pages: "dict[str, str]", digest: str) -> None:
    """Write *pages*, delete every other ``*.md``, then stamp."""
    PAGES_DIR.mkdir(parents=True, exist_ok=True)
    for stale in PAGES_DIR.glob("*.md"):
        if stale.name not in pages:
            stale.unlink()
    for name, text in pages.items():
        path = PAGES_DIR / name
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            path.write_text(text, encoding="utf-8")
    # Written aside and moved into place, so an interrupted write leaves no torn stamp.
    stamp = PAGES_DIR / STAMP
    partial = stamp.with_name(f"{STAMP}.tmp")
    partial.write_text("\n".join([digest, *pages]) + "\n", encoding="utf-8")
    partial.replace(stamp)


