def sphinx_setup(app: "Sphinx") -> None:
    """Register the release notes' Sphinx wiring on *app*; ``docs/conf.py`` calls it.

    Sphinx's smart quotes turn ``--wait`` into an en dash and ``'`` into a
    curly quote. Commit text is quoted word for word, so the pages under
    :data:`PAGES_DOCNAME` opt out, before ``SmartQuotes`` (priority 750) runs,
    and every other page keeps them.
    """
    from sphinx.transforms import SphinxTransform

    class _NoSmartQuotes(SphinxTransform):
        default_priority = 740

        def apply(self, **kwargs: object) -> None:  # noqa: ARG002 -- docutils signature
            if self.env.docname.startswith(f"{PAGES_DOCNAME}/"):
                self.document["support_smartquotes"] = False

    app.add_transform(_NoSmartQuotes)


def main(argv: "list[str]") -> int:
    """Render the pages (skipped when the stamp matches), or render and write nothing."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="render only; write nothing")
    parser.add_argument("--repo", type=Path, default=REPO_ROOT, help="the repository to read")
    parser.add_argument(
        "--print-tag-state", action="store_true", help="print the tags the pages depend on"
    )
    args = parser.parse_args(argv)
    if args.print_tag_state:
        print(tag_state(args.repo), end="")
        return 0
    try:
        if args.check:
            pages = render(args.repo)
            print(f"release notes: render ({len(pages) - 1} pages and the index)")
            return 0
        digest = _digest(args.repo)
        if _fresh(digest):
            print(f"release notes: {PAGES_DIR} is up to date")
            return 0
        pages = render(args.repo)
    except RenderError as err:
        print(f"release notes: {err}", file=sys.stderr)
        return 1
    _write(pages, digest)
    print(f"release notes: wrote {len(pages) - 1} pages and the index to {PAGES_DIR}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
