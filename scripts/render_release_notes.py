def _raw_title(entry: Entry) -> str:
    """``scope: subject`` as the commit spells it."""
    return entry.subject if entry.scope is None else f"{entry.scope}: {entry.subject}"


def _title(entry: Entry, *, bold: bool) -> str:
    """``scope: subject`` (the scope bold in a list), checked as joined.

    Each part goes through :func:`inline_text`, but two plain parts can join
    into an unplain title (a backtick in the scope pairs with one in the
    subject), so the joined title is checked again; failing that, the whole
    title as the commit spells it is one code span.
    """
    subject = inline_text(entry.subject)
    if entry.scope is None:
        title = subject
    else:
        scope = inline_text(entry.scope)
        title = f"**{scope}**: {subject}" if bold else f"{scope}: {subject}"
    if is_plain(title, inline=True):
        return title
    safe = _code_span(_lf(_raw_title(entry)))
    if not is_plain(safe, inline=True):
        raise RenderError(f"{entry.commit.sha[:12]}: no safe Markdown for {safe!r}")
    return safe


def _back_references(entry: Entry) -> "list[str]":
    """One sentence per later release that marked *entry* breaking."""
    sentences = []
    for pointer in entry.corrected_by:
        version, label = pointer.split("#")
        sentences.append(
            f"A later release ({{ref}}`{version} <{label}>`) marked this change as breaking."
        )
    return sentences


def _bullets(entries: "list[Entry]") -> "list[str]":
    if not entries:
        return ["*None in this release.*"]
    lines = []
    for entry in entries:
        bullet = f"- {_title(entry, bold=True)}"
        if entry.breaking:
            bullet += f" ([breaking](#{entry.label}))"
        lines += [bullet, *[f"  - {sentence}" for sentence in _back_references(entry)]]
    return lines


_NO_REMEDIATION = "No upgrade instructions were recorded for this change"


def _commit_message(commit: Commit) -> "list[str]":
    """Return the no-remediation note, then the collapsed message without trailers."""
    body = _lf(release_events.message_without_trailers(commit))
    if not body:
        return ["", f"*{_NO_REMEDIATION}.*"]
    note = f"*{_NO_REMEDIATION}; the commit message below describes it.*"
    inner = _fence(body, "text")
    return ["", note, "", _fence(f":collapsible:\n\n{inner}", "{admonition} Commit message")]


def _breaking_entry(entry: Entry, url: str) -> "list[str]":
    sha = entry.commit.sha
    kind = KINDS.get(entry.group, entry.group.lower())
    lines = [
        f"({entry.label})=",
        f"### {_title(entry, bold=False)}",
        "",
        f"**Kind:** {kind} · **Commit:** [{sha[:12]}]({url}/commit/{sha})",
    ]
    for correction in entry.corrects:
        target = correction.target
        original = inline_text(correction.original)
        lines += ["", f"Marks [{target[:12]}]({url}/commit/{target}) ({original}) as breaking."]
    lines += [f"\n{sentence}" for sentence in _back_references(entry)]
    if entry.remediation:
        lines += [f"\n{format_remediation(text)}" for text in entry.remediation]
    else:
        lines += _commit_message(entry.commit)
    return [*lines, ""]


def _breaking_section(entries: "list[Entry]", url: str) -> "list[str]":
    if not entries:
        return ["*None in this release.*"]
    lines = ["```{list-table}", ":header-rows: 1", "", "* - Change", "  - Kind"]
    for entry in entries:
        link = _link(_title(entry, bold=False), _raw_title(entry), f"#{entry.label}")
        lines += [f"* - {link}"]
        lines += [f"  - {KINDS.get(entry.group, entry.group.lower())}"]
    lines += ["```", ""]
    for entry in entries:
        lines += _breaking_entry(entry, url)
    return lines


def render_page(release: Release, repo_url: str) -> str:
    """Render *release*'s page: features, fixes, then every break with its remediation."""
    shown = [e for e in release.entries if e.shown]
    features = [e for e in shown if e.group == "Added"]
    fixes = [e for e in shown if e.group == "Fixed"]
    breaks = [e for e in shown if e.breaking]
    lines = [f"# otto {release.version}", "", GENERATED, "", f"Released {release.date}.", ""]
    if not shown:
        return "\n".join([*lines, "*No user-visible changes in this release.*", ""])
    if breaks:
        plural = "change" if len(breaks) == 1 else "changes"
        see = "see [Breaking changes](#breaking-changes)"
        lines.append(f"This release has {len(breaks)} breaking {plural}; {see}.")
    else:
        lines.append("No breaking changes.")
    lines += ["", "## New features", "", *_bullets(features), ""]
    lines += ["## Bug fixes", "", *_bullets(fixes), ""]
    lines += ["## Breaking changes", "", *_breaking_section(breaks, repo_url)]
    return "\n".join(lines).rstrip("\n") + "\n"


def render_index(releases: "list[Release]") -> str:
    """Render the index: intro, the CHANGELOG.md link, the floor, then every page."""
    url = repo_url()
    lines = [
        "# Release notes",
        "",
        GENERATED,
        "",
        (
            "Each page lists one otto release's new features, bug fixes and breaking "
            "changes, with what to do about each break, where one was recorded."
        ),
        f"[CHANGELOG.md]({url}/blob/main/CHANGELOG.md) lists every change, maintenance included.",
        "",
        f"The pages start at {FIRST_RELEASE}; CHANGELOG.md covers the releases before it.",
        "",
        "```{toctree}",
        ":hidden:",
        "",
        *[r.version for r in releases],
        "```",
        "",
        *[f"- [otto {r.version}]({r.version}.md), released {r.date}" for r in releases],
    ]
    return "\n".join(lines) + "\n"


def raw_html(markdown: str) -> "list[str]":
    """Return every raw-HTML token in *markdown*, inside directive bodies too."""
    found = []
    for token in myst_tokens(markdown):
        found += [t.content for t in [token, *(token.children or [])] if t.type.startswith("html")]
        if token.type == "fence" and token.info.startswith("{"):
            found += raw_html(token.content)
    return found


def _refuse_raw_html(name: str, page: str) -> None:
    """Refuse *page* if it holds raw HTML other than the :data:`GENERATED` header.

    The guard behind every fragment check: a join this script did not foresee
    cannot reach a reader silently.
    """
    leaks = [html.strip() for html in raw_html(page) if html.strip() != GENERATED]
    if leaks:
        raise RenderError(
            f"{name} would publish raw HTML from commit text: {leaks[0]!r}; "
            "the fragment checks in scripts/render_release_notes.py missed a join"
        )


def render(repo: Path) -> "dict[str, str]":
    """Render every page and the index: file name to text; refuse any raw HTML."""
    releases = read_releases(repo)
    url = repo_url()
    pages = {f"{r.version}.md": render_page(r, url) for r in releases}
    pages["index.md"] = render_index(releases)
    for name, page in pages.items():
        _refuse_raw_html(name, page)
    return pages


