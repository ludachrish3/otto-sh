DOCS_DIR = REPO_ROOT / "docs"
PAGES_DIR = DOCS_DIR / "release-notes"
PAGES_DOCNAME = PAGES_DIR.relative_to(DOCS_DIR).as_posix()
"""The pages' directory as Sphinx names its documents: ``<PAGES_DOCNAME>/<version>``."""

FIRST_RELEASE = "0.16.0"
"""The earliest version with a page (Chris, 2026-11-18). The one home of the floor."""

GENERATED = (
    "<!-- GENERATED by scripts/render_release_notes.py from the git history; do not edit -->"
)
"""The header every page carries after its heading, which the docs linters honour."""

STAMP = ".stamp"
"""The stamp file's name inside :data:`PAGES_DIR`."""

KINDS = {
    "Added": "feature",
    "Fixed": "fix",
    "Changed": "change",
    "Documentation": "docs",
    "Dependencies": "dependency",
    "Maintenance": "maintenance",
}
"""The plain word a breaking entry's Kind column shows for each git-cliff group."""

_RELEASE_TAG = re.compile(r"^v(?P<version>\d+\.\d+\.\d+(?:rc\d+)?)$")
# A code span may cross a line break but never a blank line (CommonMark: a
# blank line ends the paragraph), so a stray backtick cannot shield the `<` of
# a later paragraph.
_CODE_SPAN = re.compile(r"(?<!`)(`+)(?!`)(?:(?!\n[ \t]*\n).)+?(?<!`)\1(?!`)", re.DOTALL)
_INDENTED = re.compile(r"^ {2,}\S")
_LIST_ITEM = re.compile(r"^ ?([-*+]|\d+[.)])[ \t]+\S")
_LANGUAGE = re.compile(r"[A-Za-z0-9_+.-]*")
_SENTINEL = "release-notes-fragment-ends-here"

_BLOCK_TOKENS = frozenset(
    {
        "paragraph_open",
        "paragraph_close",
        "inline",
        "bullet_list_open",
        "bullet_list_close",
        "ordered_list_open",
        "ordered_list_close",
        "list_item_open",
        "list_item_close",
        "fence",
        "code_block",
    }
)
"""The block tokens commit text may produce: paragraphs, lists and plain code."""

_INLINE_TOKENS = frozenset(
    {
        "text",
        "softbreak",
        "hardbreak",
        "code_inline",
        "em_open",
        "em_close",
        "strong_open",
        "strong_close",
        "link_open",
        "link_close",
    }
)
"""The inline tokens commit text may produce; a link must point at http or https."""


class RenderError(Exception):
    """The pages cannot be rendered; the message names the fix."""


@dataclass
class Entry:
    """One commit on a release page."""

    commit: Commit
    group: str
    scope: "str | None"
    subject: str
    breaking: bool
    remediation: "list[str]" = field(default_factory=list)
    corrects: "list[Correction]" = field(default_factory=list)
    corrected_by: "list[str]" = field(default_factory=list)
    """``"<version>#rn-<sha12>"`` for each later entry that marked this one breaking."""

    @property
    def label(self) -> str:
        """The entry's anchor: globally unique, so ``-W`` never sees a duplicate."""
        return f"rn-{self.commit.sha[:12]}"

    @property
    def shown(self) -> bool:
        """Whether the page shows it: a user-facing feature, fix or break."""
        if release_events.is_maintainer_only(self.commit):
            return False
        return self.breaking or self.group in ("Added", "Fixed")


@dataclass
class Release:
    """One tagged release: *version* without the ``v``, *date* as YYYY-MM-DD."""

    version: str
    date: str
    entries: "list[Entry]" = field(default_factory=list)


def repo_url() -> str:
    """Return otto's GitHub URL: ``pyproject.toml``'s ``[project.urls] Source``."""
    pyproject = tomli.loads((REPO_ROOT / "pyproject.toml").read_text(encoding="utf-8"))
    return pyproject["project"]["urls"]["Source"]


def tag_state(repo: Path) -> str:
    """Return every tag merged into HEAD with its object: what the pages depend on."""
    return _git(
        repo, "for-each-ref", "refs/tags", "--merged", "HEAD", "--format=%(refname) %(objectname)"
    ).stdout


def has_page(version: str) -> bool:
    """Whether *version* is at or above :data:`FIRST_RELEASE`, compared as versions."""
    return Version(version) >= Version(FIRST_RELEASE)


