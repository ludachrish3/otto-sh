def test_the_developing_scope_is_the_developing_toctree():
    index = CHECKOUT_ROOT / "docs" / "developing" / "index.md"
    docs = CHECKOUT_ROOT / "docs"
    entries = [line.strip() for line in index.read_text().splitlines() if line.startswith("../")]
    assert len(entries) >= 3
    for entry in entries:
        stem = (index.parent / entry).resolve()
        [real] = list(stem.parent.glob(f"{stem.name}.*"))
        assert not lint.in_scope(real.relative_to(docs).as_posix())
    pages = sorted((docs / "developing").glob("*.md"))
    assert pages
    for page in pages:
        assert not lint.in_scope(page.relative_to(docs).as_posix())


