BAD = "`make kmodcov`\n"
BAD_WITH_ISSUE = "`make kmodcov` and (#1)\n"
GENERATED = "<!-- GENERATED by x; do not edit -->"


@pytest.fixture
def tree(tmp_path: Path) -> Path:
    for rel in FILES:
        (tmp_path / rel).parent.mkdir(parents=True, exist_ok=True)
        (tmp_path / rel).write_text("x\n")
    return tmp_path


def _page(tree: Path, rel: str, body: str) -> Path:
    page = tree / "docs" / rel
    page.parent.mkdir(parents=True, exist_ok=True)
    page.write_text(body)
    return page


def _rules(tree: Path, rel: str, body: str) -> list[str]:
    page = _page(tree, rel, body)
    owned = lint.Tree.of(FILES)
    return [o.rule for o in lint.page_offenses(page, tree / "docs", tree, owned)]


def _fence(body: str) -> str:
    return f"```sh\n{body}\n```\n"


def _scan_one(tmp_path: Path, rel: str, text: str) -> list[lint.Offense]:
    for name in FILES:
        (tmp_path / name).parent.mkdir(parents=True, exist_ok=True)
        (tmp_path / name).write_text("x\n")
    _page(tmp_path, rel, text)
    return lint.scan(tmp_path / "docs", tmp_path, tree=lint.Tree.of(FILES))


def _off(page: str, n: int) -> list[lint.Offense]:
    return [lint.Offense(page, i + 1, "path", f"`scripts/{i}.py`") for i in range(n)]


